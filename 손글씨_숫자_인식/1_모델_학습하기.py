# -*- coding: utf-8 -*-
"""
==========================================================
 1단계: 손글씨 숫자 인식 모델 학습하기 (Model Training)
==========================================================

이 파일이 하는 일
-----------------
1. 손글씨 숫자 사진 7만 장이 들어 있는 MNIST 데이터셋(Dataset)을 내려받습니다.
2. 사진을 컴퓨터가 배우기 좋은 형태로 바꿉니다. (전처리, Preprocessing)
3. 인공 신경망(Artificial Neural Network)에게 숫자 모양을 가르칩니다. (학습, Training)
4. 처음 보는 사진으로 얼마나 잘 맞히는지 시험합니다. (평가, Evaluation)
5. 다 배운 모델(Model)을 파일로 저장해서 2단계 프로그램이 쓸 수 있게 합니다.

실행 방법
---------
    python 1_모델_학습하기.py

※ 처음 실행할 때는 인터넷에서 데이터를 내려받느라 1~3분쯤 걸릴 수 있습니다.
※ 방법론 전체 설명은 같은 폴더의 '방법론_설명.md'에 정리되어 있습니다.


[강의 노트] 이 문제는 어떤 문제인가? — 분류(Classification)
------------------------------------------------------------
머신러닝(Machine Learning) 문제는 크게 두 가지로 나눌 수 있습니다.

  - 회귀(Regression)       : 연속된 숫자를 예측합니다.  예) 집값, 내일 기온
  - 분류(Classification)   : 정해진 보기 중 하나를 고릅니다. 예) 스팸/정상, 합격/불합격

손글씨 숫자 인식은 "이 사진은 0~9 중 무엇인가?"를 고르는 문제이므로
**분류** 문제이고, 보기가 10개이므로 **다중 클래스 분류(Multi-class Classification)** 입니다.
(보기가 2개뿐이면 이진 분류, Binary Classification)

또한 정답(라벨, Label)이 붙은 사진으로 배우므로
**지도 학습(Supervised Learning)** 에 속합니다.


[강의 노트] 머신러닝 프로젝트의 표준 절차
------------------------------------------
이 파일은 아래 순서를 그대로 따릅니다. 함수 이름 옆 번호를 따라가며 읽어 보세요.

  ① 문제 정의          → 위에서 설명 (다중 클래스 분류)
  ② 데이터 수집        → 데이터_불러오기()
  ③ 데이터 분할        → 학습용 / 검증용 / 시험용으로 나누기
  ④ 전처리             → 정규화(Normalization), 평탄화(Flatten)
  ⑤ 모델 선택·설계     → 모델_만들기()  : 다층 퍼셉트론(MLP)
  ⑥ 학습               → 모델.fit()
  ⑦ 평가               → 결과_평가하기() : 정확도, 혼동 행렬, 정밀도·재현율
  ⑧ 저장·활용          → joblib.dump() 후 2단계 프로그램에서 사용(추론, Inference)
"""

# ----------------------------------------------------------
# 필요한 도구(라이브러리, Library) 불러오기
# ----------------------------------------------------------
import gzip                                   # .gz 압축 파일을 푸는 도구
import time                                   # 걸린 시간을 재는 도구
import urllib.request                         # 인터넷에서 파일을 내려받는 도구
from pathlib import Path                      # 파일 경로(Path)를 다루는 도구

import numpy as np                            # 숫자 배열(Array) 계산 도구
import joblib                                 # 학습한 모델을 파일로 저장하는 도구
from sklearn.neural_network import MLPClassifier   # 다층 퍼셉트론(Multi-Layer Perceptron) 분류기
from sklearn.metrics import (
    accuracy_score,          # 정확도(Accuracy)
    confusion_matrix,        # 혼동 행렬(Confusion Matrix)
    classification_report,   # 클래스별 정밀도(Precision)·재현율(Recall)·F1 점수 보고서
)

# 이 파일이 있는 폴더에 모델 파일을 저장합니다.
현재_폴더 = Path(__file__).resolve().parent
모델_파일_경로 = 현재_폴더 / "숫자_인식_모델.joblib"

# 내려받은 MNIST 원본 파일을 보관할 폴더 (한 번 받으면 다음부터는 다시 받지 않습니다)
데이터_폴더 = 현재_폴더 / "mnist_데이터"
MNIST_주소 = "https://storage.googleapis.com/cvdf-datasets/mnist/"
MNIST_파일들 = {
    "학습_사진": "train-images-idx3-ubyte.gz",   # 학습용 사진 60,000장
    "학습_정답": "train-labels-idx1-ubyte.gz",   # 학습용 정답 60,000개
    "시험_사진": "t10k-images-idx3-ubyte.gz",    # 시험용 사진 10,000장
    "시험_정답": "t10k-labels-idx1-ubyte.gz",    # 시험용 정답 10,000개
}


# ==========================================================
# ② 데이터 수집
# ==========================================================
def 파일_내려받기(파일_이름):
    """MNIST 파일 하나를 내려받습니다. 이미 있으면 건너뜁니다. (캐시, Cache)"""
    데이터_폴더.mkdir(exist_ok=True)
    저장_경로 = 데이터_폴더 / 파일_이름
    if not 저장_경로.exists():
        print(f"   ↓ 내려받는 중: {파일_이름}")
        urllib.request.urlretrieve(MNIST_주소 + 파일_이름, 저장_경로)
    return 저장_경로


def IDX_파일_읽기(경로, 머리말_크기):
    """
    MNIST 원본 파일(IDX 형식)을 숫자 배열로 읽습니다.

    IDX 형식이란?
      - 파일 맨 앞에 '머리말(Header)'이 있고, 그 뒤에 숫자들이 한 바이트(Byte, 0~255)씩 쭉 이어집니다.
      - 사진 파일의 머리말은 16바이트, 정답 파일의 머리말은 8바이트입니다.
      - 머리말을 건너뛰고 나머지를 그대로 읽으면 됩니다.
    """
    with gzip.open(경로, "rb") as 파일:
        # uint8: 0~255를 담는 1바이트 정수. 메모리를 아주 적게 씁니다.
        return np.frombuffer(파일.read(), dtype=np.uint8, offset=머리말_크기)


def 데이터_불러오기():
    """
    MNIST 데이터셋을 내려받아 학습용(Training set)과 시험용(Test set)으로 나눕니다.

    MNIST란?
      - 사람들이 손으로 쓴 0~9 숫자 사진 70,000장 모음입니다.
      - 사진 한 장은 가로 28칸 × 세로 28칸 = 784개의 점(픽셀, Pixel)으로 되어 있습니다.
      - 각 픽셀은 0(검은색) ~ 255(흰색) 사이의 밝기 값을 가집니다.
      - 배경은 검은색, 글씨는 흰색입니다.

    [강의 노트] 데이터를 표(Table)로 생각하기
      분류 강의에서 흔히 보는 표 형태 데이터와 똑같이 생각할 수 있습니다.
        - 행(Row)    = 사진 한 장 = 표본(Sample) 하나         → 60,000행
        - 열(Column) = 픽셀 하나 = 특징(Feature) 또는 입력 변수 → 784열
        - 정답 열    = 목표 변수(Target, y) = 0~9 중 하나
      즉 "784개의 입력 변수로 10개 범주 중 하나를 예측하는 분류 문제"입니다.
      보통 입력은 대문자 X, 정답은 소문자 y로 씁니다.
    """
    print("📥 [② 데이터 수집] MNIST 데이터셋을 불러오는 중입니다... (처음에는 내려받느라 조금 걸려요)")

    경로 = {이름: 파일_내려받기(파일) for 이름, 파일 in MNIST_파일들.items()}

    # 입력 데이터(X): 사진들, 정답(y): 각 사진이 어떤 숫자인지
    # reshape(-1, 784): 쭉 이어진 숫자들을 '사진 한 장 = 784개' 단위로 자릅니다.
    #   [강의 노트] 평탄화(Flatten)
    #   원래 사진은 28×28 '격자'지만, MLP는 입력을 '한 줄짜리 목록'으로만 받습니다.
    #   그래서 28줄을 옆으로 이어 붙여 784칸짜리 한 줄로 폅니다.
    #   이때 "어느 픽셀이 어느 픽셀 옆에 있었는지"라는 위치 정보는 모델이 직접 알 수 없게 됩니다.
    #   (이 약점을 보완한 것이 합성곱 신경망 CNN입니다. 방법론_설명.md 참고)
    학습_사진 = IDX_파일_읽기(경로["학습_사진"], 16).reshape(-1, 784)
    시험_사진 = IDX_파일_읽기(경로["시험_사진"], 16).reshape(-1, 784)
    학습_정답 = IDX_파일_읽기(경로["학습_정답"], 8).astype(int)
    시험_정답 = IDX_파일_읽기(경로["시험_정답"], 8).astype(int)

    # ------------------------------------------------------
    # ③ 데이터 분할 (Data Split)
    # ------------------------------------------------------
    # [강의 노트] 왜 나누나요?
    #   모델이 '외워서' 맞히는지 '이해해서' 맞히는지 알려면, 공부할 때 본 적 없는 문제로 시험해야 합니다.
    #     - 학습 데이터(Training set)   54,000장 : 모델이 보고 공부하는 교과서
    #     - 검증 데이터(Validation set)  6,000장 : 공부 중간에 보는 모의고사 (언제 멈출지 결정)
    #     - 시험 데이터(Test set)       10,000장 : 맨 마지막에 딱 한 번 보는 수능
    #   MNIST는 학습용 60,000장 / 시험용 10,000장이 처음부터 다른 파일로 나뉘어 있습니다.
    #   검증용 6,000장(학습용의 10%)은 모델_만들기()의 validation_fraction=0.1 설정으로
    #   학습 도중 sklearn이 자동으로 떼어 냅니다.
    #   ※ 시험 데이터는 학습·조정 과정에서 절대 보면 안 됩니다. 보는 순간 '유출(Data Leakage)'이 됩니다.

    # ------------------------------------------------------
    # ④ 전처리 (Preprocessing) — 정규화(Normalization)
    # ------------------------------------------------------
    # 0~255 값을 0~1 사이로 줄입니다. (최소-최대 정규화, Min-Max Scaling: x / 255)
    # [강의 노트] 왜 필요한가요?
    #   신경망은 입력에 가중치(Weight)를 곱해 더하는 계산을 반복합니다.
    #   입력이 0~255처럼 크면 계산 결과가 너무 커져서 학습이 불안정해지고 느려집니다.
    #   모든 입력을 비슷한 작은 범위로 맞추면 경사 하강법이 훨씬 안정적으로 움직입니다.
    #   ※ 2단계에서 직접 쓴 그림을 넣을 때도 '똑같이' 255로 나눠야 합니다.
    #     학습할 때와 사용할 때의 전처리가 다르면 성능이 크게 떨어집니다.
    # float32: 소수를 담는 4바이트 실수. float64보다 메모리를 절반만 씁니다.
    학습_사진 = 학습_사진.astype(np.float32) / 255.0
    시험_사진 = 시험_사진.astype(np.float32) / 255.0

    print(f"   ✔ 학습용 사진: {len(학습_사진):,}장 (이 중 10%는 검증용) / 시험용 사진: {len(시험_사진):,}장")
    print(f"   ✔ 사진 한 장의 특징(픽셀) 수: {학습_사진.shape[1]}개 (28 × 28)")
    return 학습_사진, 시험_사진, 학습_정답, 시험_정답


# ==========================================================
# ⑤ 모델 선택·설계 — 다층 퍼셉트론 (MLP)
# ==========================================================
def 모델_만들기():
    """
    인공 신경망 모델을 만듭니다.

    구조(Architecture)
      입력층(Input layer)   : 784개  ← 사진의 픽셀 784개가 들어옵니다.
      은닉층1(Hidden layer) : 256개  ← 선, 곡선 같은 작은 특징(Feature)을 찾습니다.
      은닉층2(Hidden layer) : 128개  ← 작은 특징을 모아 더 큰 모양을 알아봅니다.
      출력층(Output layer)  : 10개   ← 0~9 각각일 확률(Probability)을 냅니다.

    [강의 노트] 뉴런(Neuron) 하나가 하는 일
      ① 입력마다 '중요도'인 가중치(Weight, w)를 곱합니다.
      ② 모두 더한 뒤 편향(Bias, b)을 더합니다.          z = w1·x1 + w2·x2 + ... + b
      ③ 활성화 함수(Activation function)를 통과시킵니다.  출력 = ReLU(z) = max(0, z)
      → 로지스틱 회귀(Logistic Regression)와 거의 같은 계산을 하는 작은 판단 장치입니다.
        이런 뉴런을 여러 층으로 쌓은 것이 다층 퍼셉트론(MLP)입니다.

    [강의 노트] 왜 활성화 함수가 필요한가요?
      곱하고 더하기(선형 계산)만 여러 번 하면, 아무리 층을 쌓아도 결국 '직선 하나'와 같습니다.
      ReLU처럼 꺾인 함수를 중간에 넣어야 구불구불한 경계도 배울 수 있습니다. (비선형성, Non-linearity)

    [강의 노트] 출력층 — 소프트맥스(Softmax)
      출력층 뉴런 10개가 낸 점수를 '모두 더하면 1이 되는 확률' 10개로 바꿉니다.
      예) [숫자0: 0.01, ..., 숫자7: 0.93, ...] → 가장 큰 7을 정답으로 고릅니다.
      다중 클래스 분류이므로 sklearn이 출력층에 자동으로 소프트맥스를 씁니다.

    [강의 노트] 모델이 배워야 할 숫자(파라미터, Parameter)의 개수
      입력→은닉1 : 784 × 256 + 256(편향) = 200,960개
      은닉1→은닉2: 256 × 128 + 128       =  32,896개
      은닉2→출력 : 128 × 10  + 10        =   1,290개
      합계                                = 235,146개
      학습이란 이 23만여 개의 숫자를 '정답을 잘 맞히는 값'으로 조금씩 맞춰 가는 과정입니다.
    """
    모델 = MLPClassifier(
        # --- 구조 관련 ---
        hidden_layer_sizes=(256, 128),  # 은닉층 두 개, 뉴런(Neuron) 수는 256개와 128개
        activation="relu",              # 활성화 함수(Activation function): ReLU (음수는 0, 양수는 그대로)

        # --- 학습 방법 관련 ---
        # [강의 노트] 손실 함수(Loss function)는 따로 적지 않아도
        #   분류 문제에서는 교차 엔트로피(Cross-Entropy, Log-loss)가 자동으로 쓰입니다.
        #   정답 숫자에 준 확률이 높을수록 손실이 작아집니다. 손실 = -log(정답 클래스의 확률)
        #   예) 정답이 7인데 7일 확률을 0.9로 예측 → 손실 0.105 / 0.1로 예측 → 손실 2.303
        solver="adam",                  # 최적화 방법(Optimizer): Adam
                                        #   경사 하강법(Gradient Descent)을 개선한 방법으로,
                                        #   가중치마다 보폭을 자동으로 조절해 빠르고 안정적으로 배웁니다.
        learning_rate_init=1e-3,        # 학습률(Learning rate) = 0.001: 한 번 고칠 때의 보폭
                                        #   너무 크면 정답 근처를 지나쳐 버리고, 너무 작으면 한참 걸립니다.
        batch_size=128,                 # 미니 배치(Mini-batch): 한 번에 128장씩 보고 가중치를 고칩니다
                                        #   54,000장 ÷ 128장 ≈ 422번 고치면 데이터 전체를 한 바퀴 봅니다.
        max_iter=30,                    # 최대 에포크(Epoch) 수: 데이터 전체를 최대 30바퀴 봅니다
                                        #   (sklearn에서는 iteration이 '에포크'를 뜻합니다)

        # --- 과적합(Overfitting) 방지 관련 ---
        # [강의 노트] 과적합이란? 교과서 문제의 답만 외워서, 새 문제는 못 푸는 상태.
        alpha=1e-4,                     # L2 규제(L2 Regularization) 강도
                                        #   가중치가 지나치게 커지면 손실에 벌점을 더해,
                                        #   모델이 특정 픽셀 몇 개에만 과하게 의존하지 않게 합니다.
        early_stopping=True,            # 조기 종료(Early stopping)
        validation_fraction=0.1,        #   학습 데이터의 10%(6,000장)를 검증용으로 떼어 두고,
        n_iter_no_change=4,             #   검증 정확도가 4에포크 연속 나아지지 않으면 멈춘 뒤
                                        #   검증 점수가 가장 좋았던 때의 가중치로 되돌립니다.

        # --- 기타 ---
        random_state=42,                # 난수 시드(Random seed): 가중치 초깃값·데이터 섞는 순서를 고정
                                        #   → 누가 실행해도 같은 결과가 나와 수업에서 비교하기 좋습니다.
        verbose=True,                   # 에포크마다 손실(loss)과 검증 점수를 화면에 보여 줍니다
    )
    return 모델


