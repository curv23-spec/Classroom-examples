# 전체 실행 순서
# ==========================================================
def main():
    시작_시각 = time.time()

    # ②③④ 데이터 수집·분할·전처리
    학습_사진, 시험_사진, 학습_정답, 시험_정답 = 데이터_불러오기()

    # ⑤ 모델 만들기
    모델 = 모델_만들기()

    # ⑥ 학습 (Training)
    # [강의 노트] fit() 안에서 일어나는 일 — 한 번의 '가중치 고치기'(1 step)
    #   1) 순전파(Forward propagation): 사진 128장을 넣어 각 숫자일 확률을 계산합니다.
    #   2) 손실 계산(Loss): 예측 확률과 정답을 비교해 '얼마나 틀렸는지'를 숫자 하나로 냅니다.
    #   3) 역전파(Backpropagation): 손실을 줄이려면 각 가중치를 어느 방향으로 얼마나
    #      바꿔야 하는지(기울기, Gradient)를 출력층에서 입력층 쪽으로 거꾸로 계산합니다.
    #   4) 가중치 갱신(Update): Adam이 기울기의 반대 방향으로 학습률만큼 가중치를 옮깁니다.
    #   → 이것을 미니 배치마다 반복(약 422번 = 1에포크)하고, 에포크마다 검증 점수를 확인합니다.
    #
    # 화면 읽는 법
    #   Iteration N, loss = ...   : N번째 에포크의 평균 손실. 점점 작아지면 잘 배우는 중.
    #   Validation score: ...     : 검증 데이터 정확도. 이 값이 더 오르지 않으면 조기 종료.
    print("\n🧠 [⑥ 학습] 신경망 학습을 시작합니다.")
    모델.fit(학습_사진, 학습_정답)
    print(f"\n   ✔ 학습 완료: 에포크 {모델.n_iter_}번 진행")
    print(f"   ✔ 가장 좋았던 검증 정확도: {모델.best_validation_score_ * 100:.2f}%")

    # ⑦ 평가
    결과_평가하기(모델, 시험_사진, 시험_정답)

    # ⑧ 저장 — 학습된 가중치 23만여 개가 들어 있는 모델을 파일로 보관합니다.
    #   다음부터는 다시 학습하지 않고 이 파일만 불러와 바로 예측(추론, Inference)할 수 있습니다.
    joblib.dump(모델, 모델_파일_경로)
    print(f"\n💾 [⑧ 저장] 모델을 저장했습니다: {모델_파일_경로.name}")
    print(f"⏱  전체 걸린 시간: {time.time() - 시작_시각:.1f}초")
    print("\n✅ 이제 '2_손글씨_숫자_인식하기.py'를 실행해서 직접 숫자를 써 보세요!")


# 이 파일을 직접 실행했을 때만 main()을 실행합니다.
if __name__ == "__main__":
    main()
