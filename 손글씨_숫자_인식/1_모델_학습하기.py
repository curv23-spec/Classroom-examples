# ⑦ 평가
# ==========================================================
def 결과_평가하기(모델, 시험_사진, 시험_정답):
    """
    처음 보는 시험 데이터 10,000장으로 모델의 실력을 여러 각도에서 확인합니다.

    [강의 노트] 분류 모델 평가 지표(Metric)
      - 정확도(Accuracy)  : 전체 중 맞힌 비율. 가장 직관적이지만, 클래스 비율이 한쪽으로 치우치면 착시가 생깁니다.
      - 정밀도(Precision) : 모델이 "7이다"라고 한 것 중 진짜 7인 비율  → 헛다리를 얼마나 덜 짚나
      - 재현율(Recall)    : 진짜 7 중에서 모델이 7로 찾아낸 비율       → 놓치는 것이 얼마나 적나
      - F1 점수(F1-score) : 정밀도와 재현율의 조화 평균. 둘 다 높아야 높게 나옵니다.
      - 혼동 행렬(Confusion Matrix): 행=실제 정답, 열=모델 예측. 대각선이 맞힌 개수, 나머지는 '무엇을 무엇으로 착각했는지'.
    """
    print("\n📝 [⑦ 평가] 시험 데이터로 평가합니다.")

    # predict(): 각 사진에서 확률이 가장 높은 숫자를 예측값으로 돌려줍니다.
    예측들 = 모델.predict(시험_사진)
    정확도 = accuracy_score(시험_정답, 예측들)
    print(f"\n   정확도(Accuracy): {정확도 * 100:.2f}%")
    print(f"   → 10,000장 중 {int(round(정확도 * 10000)):,}장을 맞혔어요!")

    # 클래스(숫자)별 정밀도·재현율·F1 점수
    # support = 그 숫자의 시험 사진 개수
    print("\n🔢 숫자별 정밀도(precision)·재현율(recall)·F1 점수 (support = 사진 개수)")
    print(classification_report(시험_정답, 예측들, digits=3))

    # 혼동 행렬에서 가장 많이 헷갈린 짝 찾기
    표 = confusion_matrix(시험_정답, 예측들)
    틀린_표 = 표.copy()
    np.fill_diagonal(틀린_표, 0)                    # 대각선(맞힌 것)은 빼고 틀린 것만 봅니다.
    print("🤔 모델이 가장 많이 헷갈린 숫자 (실제 → 예측)")
    가장_많은_순서 = np.argsort(틀린_표, axis=None)[::-1][:5]
    for 위치 in 가장_많은_순서:
        실제, 예측 = np.unravel_index(위치, 틀린_표.shape)
        print(f"   실제 {실제} → {예측}(으)로 착각: {틀린_표[실제, 예측]}번")


